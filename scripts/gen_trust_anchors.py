# Generates BearSSL trust anchors (br_x509_trust_anchor) from PEM root certificates.
# Usage: python3 gen_ta.py OUT.h NAME cert1.pem [cert2.pem ...]
import sys
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec

out, name, files = sys.argv[1], sys.argv[2], sys.argv[3:]
def arr(n, b):
    lines = ['static const unsigned char %s[] = {' % n]
    for i in range(0, len(b), 12):
        lines.append('  ' + ', '.join('0x%02x' % x for x in b[i:i+12]) + ',')
    lines.append('};')
    return '\n'.join(lines)
body, entries = [], []
for i, f in enumerate(files):
    c = x509.load_pem_x509_certificate(open(f, 'rb').read())
    dn = c.subject.public_bytes()
    body.append('// %s (expires %s)' % (c.subject.rfc4514_string(), c.not_valid_after_utc.date()))
    body.append(arr('%s_DN%d' % (name, i), dn))
    k = c.public_key()
    if isinstance(k, rsa.RSAPublicKey):
        n = k.public_numbers().n; e = k.public_numbers().e
        nb = n.to_bytes((n.bit_length() + 7) // 8, 'big'); eb = e.to_bytes((e.bit_length() + 7) // 8, 'big')
        body.append(arr('%s_N%d' % (name, i), nb)); body.append(arr('%s_E%d' % (name, i), eb))
        entries.append('  {{(unsigned char*)%s_DN%d, sizeof(%s_DN%d)}, BR_X509_TA_CA, {BR_KEYTYPE_RSA, {{(unsigned char*)%s_N%d, sizeof(%s_N%d), (unsigned char*)%s_E%d, sizeof(%s_E%d)}}}},'
                       % ((name, i) * 6))
    else:
        raise SystemExit('only RSA roots supported: ' + f)
src = ['// Root certificates trusted for api.telegram.org, as BearSSL trust anchors.\n// Generated by scripts/gen_trust_anchors.py from the PEM files listed below. Do not edit.\n//\n// api.telegram.org is signed by "Go Daddy Secure Certificate Authority - G2", which chains to\n// the Go Daddy Root G2. Starfield Root G2 (same company) and ISRG Root X1 (Let\'s Encrypt) are\n// spares in case Telegram changes its certificate authority. These arrays stay in RAM (about\n// 1.5 kB): BearSSL reads them byte by byte, which the ESP8266 cannot do from flash.', '#pragma once', '', '#include <bearssl/bearssl.h>', '']
src += body
src += ['', 'static const br_x509_trust_anchor %s[] = {' % name] + entries + ['};', 'static const size_t %s_COUNT = sizeof(%s) / sizeof(%s[0]);' % (name, name, name), '']
open(out, 'w').write('\n'.join(src))
